let commandIndex = 0;
let charIndex = 0;
let isTyping = false;

function typeTerminal() {
    const currentCommands = terminalCommandsData['en'];
    
    if (commandIndex >= currentCommands.length) {
        // Add blinking cursor at the end
        if(!document.querySelector('.cursor')) {
            terminalBody.innerHTML += '<span class="cursor"></span>';
        }
        isTyping = false;
        return;
    }

    isTyping = true;
    const currentCommand = currentCommands[commandIndex];
    
    if (charIndex === 0) {
        // Create new line element
        const line = document.createElement('div');
        line.id = `line-${commandIndex}`;
        line.style.color = currentCommand.color;
        
        // Remove previous cursor if exists
        const prevCursor = document.querySelector('.cursor');
        if (prevCursor) prevCursor.remove();
        
        // Add prompt for first line
        if (commandIndex === 0) {
            line.innerHTML = '<span style="color:#27c93f">$ </span><span class="text-content"></span><span class="cursor"></span>';
        } else {
            line.innerHTML = '<span class="text-content"></span><span class="cursor"></span>';
        }
        
        terminalBody.appendChild(line);
    }
    
    const lineElement = document.getElementById(`line-${commandIndex}`);
    if(!lineElement) return; // safety check
    
    const textContentElement = lineElement.querySelector('.text-content');
    
    if (charIndex < currentCommand.text.length) {
        textContentElement.innerHTML += currentCommand.text.charAt(charIndex);
        charIndex++;
        // Auto-scroll terminal internally — page position stays fixed
        terminalBody.scrollTop = terminalBody.scrollHeight;
        // Random typing speed for realism
        const typingSpeed = currentCommand.text.startsWith('[+') || currentCommand.text.startsWith('[✔]') ? 10 : Math.random() * 50 + 20;
        setTimeout(typeTerminal, typingSpeed);
    } else {
        commandIndex++;
        charIndex = 0;
        // Pause between commands
        setTimeout(typeTerminal, 400);
    }
}

// Start terminal typing when section is in view
const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            if(!isTyping) {
                terminalBody.innerHTML = '';
                commandIndex = 0;
                charIndex = 0;
                setTimeout(typeTerminal, 500);
            }
        }
    });
}, { threshold: 0.5 });

observer.observe(document.querySelector('.terminal-window'));

